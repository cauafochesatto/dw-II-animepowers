/**
 * Função de sorteio ponderado de acordo com as probabilidades configuradas.
 */
export function rollRandomCharacter() {
  const rand = Math.random() * 100;
  let cumulative = 0;
  let chosenRarity = RARITIES.COMUM;

  // Percorre as raridades por taxa
  const rarityOrder = [
    RARITIES.MITICO,
    RARITIES.LENDARIO,
    RARITIES.EPICO,
    RARITIES.RARO,
    RARITIES.INCOMUM,
    RARITIES.COMUM,
  ];

  for (const rarity of rarityOrder) {
    cumulative += RARITY_CONFIG[rarity].rate;
    if (rand <= cumulative) {
      chosenRarity = rarity;
      break;
    }
  }

  const pool = CHARACTERS.filter((c) => c.raridade === chosenRarity);
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex] || CHARACTERS[0];
}

/**
 * Calcula a classificação da construção com base nos atributos, média e equilíbrio.
 * Ranks: D, C, B, A, S, SS, SSS.
 */
export function calculateBuildClassification(stats) {
  if (!stats) return { rank: 'D', score: 50, color: '#94a3b8', label: 'Iniciante' };

  const values = [
    stats.forca || 50,
    stats.velocidade || 50,
    stats.defesa || 50,
    stats.resistencia || 50,
    stats.energia || 50,
    stats.poderEspecial || 50,
  ];

  const sum = values.reduce((acc, v) => acc + v, 0);
  const mean = sum / values.length;

  // Desvio padrão para avaliar equilíbrio
  const variance = values.reduce((acc, v) => acc + Math.pow(v - mean, 2), 0) / values.length;
  const stdDev = Math.sqrt(variance);

  // Bônus de sinergia/equilíbrio (até +6 pontos quando bem distribuído)
  const balanceBonus = Math.max(0, 6 - stdDev * 0.45);
  const finalScore = mean + balanceBonus;

  if (finalScore >= 96) {
    return { rank: 'SSS', score: Math.round(finalScore), color: '#ef4444', label: 'Divino Supremo', glow: '0 0 25px rgba(239,68,68,0.7)' };
  }
  if (finalScore >= 92) {
    return { rank: 'SS', score: Math.round(finalScore), color: '#ec4899', label: 'Transcendente', glow: '0 0 20px rgba(236,72,153,0.6)' };
  }
  if (finalScore >= 87) {
    return { rank: 'S', score: Math.round(finalScore), color: '#f59e0b', label: 'Mítico / Lendário', glow: '0 0 16px rgba(245,158,11,0.55)' };
  }
  if (finalScore >= 80) {
    return { rank: 'A', score: Math.round(finalScore), color: '#a855f7', label: 'Mestre Elite', glow: '0 0 12px rgba(168,85,247,0.45)' };
  }
  if (finalScore >= 73) {
    return { rank: 'B', score: Math.round(finalScore), color: '#0ea5e9', label: 'Veterano', glow: '0 0 8px rgba(14,165,233,0.35)' };
  }
  if (finalScore >= 65) {
    return { rank: 'C', score: Math.round(finalScore), color: '#10b981', label: 'Combatente', glow: 'none' };
  }
  return { rank: 'D', score: Math.round(finalScore), color: '#94a3b8', label: 'Aprendiz', glow: 'none' };
}
